export const DICTIONARIES = { en, ru } as const;
export type Locale = keyof typeof DICTIONARIES;

export function currentLocale(): Locale {
  const lang = typeof document === "undefined" ? "" : document.documentElement.lang;
  return lang.toLowerCase().startsWith("ru") ? "ru" : "en";
}

function format(template: string, vars?: Record<string, string | number>): string {
  if (vars === undefined) return template;
  return template.replace(/\{(\w+)\}/gu, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

function subscribeLang(onChange: () => void): () => void {
  if (typeof MutationObserver === "undefined" || typeof document === "undefined") return () => {};
  const observer = new MutationObserver(onChange);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ["lang"] });
  return () => observer.disconnect();
}

/** Re-render when BB switches `<html lang>` (it can change after the bundle loads). Call it in
 * every root component; children read the locale through t() on that render. */
export function useLocale(): Locale {
  return useSyncExternalStore(subscribeLang, currentLocale, () => "en" as Locale);
}

/** Translate a known key. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  return format(DICTIONARIES[currentLocale()][key], vars);
}

/** Translate a key built at runtime (status, type, stage); falls back to `fallback`. */
export function tMaybe(key: string, fallback: string): string {
  const dictionary: Record<string, string> = DICTIONARIES[currentLocale()];
  return Object.prototype.hasOwnProperty.call(dictionary, key) ? (dictionary[key] as string) : fallback;
}

export function formatDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return date.toLocaleString(currentLocale() === "ru" ? "ru-RU" : "en-GB", {
    day: "numeric",
    month: "short",
    hour: "2-digit",
    minute: "2-digit",
  });
}
